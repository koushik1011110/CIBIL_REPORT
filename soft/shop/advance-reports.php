            $sql = "SELECT p.*, f.application_no, c.name as cust_name, c.mobile as cust_mobile, s.name as shop_name FROM payments p JOIN finance_applications f ON f.id = p.finance_id JOIN customers c ON c.id = p.customer_id LEFT JOIN shops s ON s.id = f.shop_id WHERE p.remarks LIKE '%foreclosure%' OR p.remarks LIKE '%settlement%' OR p.remarks LIKE '%full%' ORDER BY p.paid_at DESC";
