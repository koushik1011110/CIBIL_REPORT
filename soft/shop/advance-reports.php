            $sql = "SELECT DATE_FORMAT(p.paid_at, '%Y-%m') as y_m, COUNT(*) as tx_count, SUM(CASE WHEN p.payment_method = 'cash' THEN p.amount ELSE 0 END) as cash_amt, SUM(CASE WHEN p.payment_method != 'cash' THEN p.amount ELSE 0 END) as online_amt, SUM(p.amount) as total_amt FROM payments p JOIN finance_applications f ON f.id = p.finance_id WHERE DATE(p.paid_at) BETWEEN ? AND ?";
