if ($reportType === 'portfolio_summary') {
    $kpiShopSql = ($selectedShopId > 0) ? " WHERE shop_id = {$selectedShopId}" : "";
    $kpiShopSqlJoin = ($selectedShopId > 0) ? " JOIN finance_applications fa ON fa.id = p.finance_id WHERE fa.shop_id = {$selectedShopId}" : "";
    $kpiShopSqlEmi = ($selectedShopId > 0) ? " JOIN finance_applications fa ON fa.id = e.finance_id WHERE fa.shop_id = {$selectedShopId}" : "";

    $kpiTotalLoans     = (int)$p->query("SELECT COUNT(*) FROM finance_applications {$kpiShopSql}")->fetchColumn();
    $kpiTotalFinanced  = (float)$p->query("SELECT COALESCE(SUM(finance_amount), 0) FROM finance_applications {$kpiShopSql}")->fetchColumn();
    $kpiTotalPayable   = (float)$p->query("SELECT COALESCE(SUM(total_payable), 0) FROM finance_applications {$kpiShopSql}")->fetchColumn();
    $kpiTotalCollected = (float)$p->query("SELECT COALESCE(SUM(p.amount), 0) FROM payments p {$kpiShopSqlJoin}")->fetchColumn();
    $kpiTotalOverdue   = (float)$p->query("SELECT COALESCE(SUM(e.amount), 0) FROM emi_schedules e {$kpiShopSqlEmi} " . ($selectedShopId > 0 ? " AND" : " WHERE") . " e.status != 'paid' AND e.due_date < CURRENT_DATE")->fetchColumn();
    $kpiTotalPending   = (float)$p->query("SELECT COALESCE(SUM(e.amount), 0) FROM emi_schedules e {$kpiShopSqlEmi} " . ($selectedShopId > 0 ? " AND" : " WHERE") . " e.status != 'paid'")->fetchColumn();
    $kpiOutstanding    = max(0, $kpiTotalPayable - $kpiTotalCollected);
    $kpiEfficiency     = $kpiTotalPayable > 0 ? round(($kpiTotalCollected / $kpiTotalPayable) * 100, 1) : 0;
    $kpiParRatio       = $kpiTotalPayable > 0 ? round(($kpiTotalOverdue / $kpiTotalPayable) * 100, 1) : 0;
}

