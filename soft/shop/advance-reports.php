            }
            break;

        default: // portfolio_summary
            fputcsv($out, ['Metric KPI', 'Value', 'Details']);
            $tFinanced = (float)$p->query("SELECT COALESCE(SUM(finance_amount), 0) FROM finance_applications")->fetchColumn();
            $tPayable  = (float)$p->query("SELECT COALESCE(SUM(total_payable), 0) FROM finance_applications")->fetchColumn();
            $tCollected = (float)$p->query("SELECT COALESCE(SUM(amount), 0) FROM payments")->fetchColumn();
            $tOverdue   = (float)$p->query("SELECT COALESCE(SUM(amount), 0) FROM emi_schedules WHERE status != 'paid' AND due_date < CURRENT_DATE")->fetchColumn();
            $tPending   = (float)$p->query("SELECT COALESCE(SUM(amount), 0) FROM emi_schedules WHERE status != 'paid'")->fetchColumn();
            $outBal     = max(0, $tPayable - $tCollected);
            $effRate    = $tPayable > 0 ? round(($tCollected / $tPayable) * 100, 1) : 0;
            
            fputcsv($out, ['Total Financed Capital (Gross Book)', $tFinanced, 'Cumulative value of all loans approved']);
            fputcsv($out, ['Total Contracted Payable', $tPayable, 'Principal plus total interest booked']);
            fputcsv($out, ['Total Realized Recovery (Collections)', $tCollected, 'Actual cash & digital payments received']);
            fputcsv($out, ['Net Outstanding Portfolio Balance', $outBal, 'Current remaining borrower loan balance']);
            fputcsv($out, ['Overdue Default Amount (At Risk)', $tOverdue, 'Unpaid installments past calendar due date']);
            fputcsv($out, ['Gross Portfolio Collection Efficiency', $effRate . '%', 'Percentage of recovery vs total payable']);
            break;
    }

    fclose($out);
    exit;
}

